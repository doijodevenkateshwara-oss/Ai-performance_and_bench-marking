"""Root locustfile — locust CLI only accepts .py paths, so this thin shim
re-exports the User classes and load shape generated by llm_perf.locustfile."""

from locust import LoadTestShape, User

import llm_perf.locustfile as _llm

_seen = set()
for _name in dir(_llm):
    _obj = getattr(_llm, _name)
    if not (
        isinstance(_obj, type)
        and _obj is not User
        and _obj is not LoadTestShape
        and id(_obj) not in _seen
        and (issubclass(_obj, User) or issubclass(_obj, LoadTestShape))
    ):
        continue
    _seen.add(id(_obj))
    globals()[_name] = _obj
