"""Root locustfile — locust CLI only accepts .py paths, so this thin shim
re-exports the User classes generated by llm_perf.locustfile."""

from locust import User

import llm_perf.locustfile as _llm

_seen = set()
for _name in dir(_llm):
    _obj = getattr(_llm, _name)
    if isinstance(_obj, type) and issubclass(_obj, User) and _obj is not User and id(_obj) not in _seen:
        _seen.add(id(_obj))
        globals()[_name] = _obj
