"""Resilience execution engine for retries, circuit breakers, and fallbacks.

Policies are evaluated at dependency boundaries (provider calls, vector stores,
agent tools, and app endpoints). State is per process and per call site; in a
distributed Locust run every worker owns its own breaker state.


Author: Venkateshwara Doijode
"""

from __future__ import annotations

import random
import threading
import time
from collections import deque
from collections.abc import Callable
from dataclasses import dataclass
from typing import Any

import requests

from .config import CircuitBreakerPolicy, ResilienceConfig, RetryPolicy
from .metrics import record_resilience_event, reset_resilience_metrics


class InjectedFault(Exception):
    """Fault generated by resilience.fault_injection."""

    def __init__(self, kind: str, message: str = "injected fault"):
        """InjectedFault(kind, message)."""
        super().__init__(message)
        self.kind = kind


class OperationFailed(Exception):
    """A dependency call completed all attempts but still failed."""

    def __init__(self, kind: str, message: str, result: Any = None):
        """OperationFailed(kind, message, result)."""
        super().__init__(message)
        self.kind = kind
        self.result = result


class CircuitOpen(Exception):
    """Raised when a call is rejected without hitting the dependency."""


@dataclass
class ResilientResult:
    """Result of a dependency call plus resilience metadata."""

    value: Any
    degraded: bool = False
    fallback_used: bool = False
    attempts: int = 1


@dataclass
class _FailureInfo:
    """Normalized failure classification."""

    kind: str
    message: str
    result: Any = None


@dataclass
class _Permit:
    """One call admitted through a breaker."""

    allowed: bool
    half_open: bool = False


class CircuitBreaker:
    """Concurrency-safe closed/open/half-open breaker for one call site."""

    def __init__(
        self,
        policy: CircuitBreakerPolicy,
        scenario: str,
        target: str,
        site: str,
    ):
        """CircuitBreaker(policy, scenario, target, site)."""
        self.policy = policy
        self.scenario = scenario
        self.target = target
        self.site = site
        self.state = "closed"
        self._failures: deque[float] = deque()
        self._opened_at = 0.0
        self._half_open_inflight = 0
        self._half_open_successes = 0
        self._lock = threading.Lock()

    def _event(self, event: str, value: float = 1.0) -> None:
        """Publish one breaker metric/snapshot event."""
        record_resilience_event(self.scenario, self.target, self.site, event, value)

    def acquire(self) -> _Permit:
        """Return whether a call may proceed; transitions OPEN -> HALF_OPEN."""
        now = time.monotonic()
        with self._lock:
            if self.state == "closed":
                return _Permit(True)
            if self.state == "open":
                if now - self._opened_at >= self.policy.open_duration_s:
                    self.state = "half_open"
                    self._half_open_inflight = 0
                    self._half_open_successes = 0
                    self._event("circuit_half_open")
                else:
                    return _Permit(False)
            if self.state == "half_open" and self._half_open_inflight < self.policy.half_open_calls:
                self._half_open_inflight += 1
                return _Permit(True, half_open=True)
            return _Permit(False)

    def success(self, permit: _Permit) -> None:
        """Record a successful dependency call."""
        with self._lock:
            self._failures.clear()
            if not permit.half_open:
                return
            self._half_open_inflight = max(self._half_open_inflight - 1, 0)
            self._half_open_successes += 1
            if self._half_open_successes >= self.policy.successes_to_close:
                self.state = "closed"
                self._half_open_inflight = 0
                self._half_open_successes = 0
                self._event("circuit_closed")

    def failure(self, permit: _Permit) -> None:
        """Record a failed dependency call and open when threshold is reached."""
        now = time.monotonic()
        with self._lock:
            if permit.half_open:
                self._half_open_inflight = max(self._half_open_inflight - 1, 0)
                self._open(now)
                return
            self._failures.append(now)
            while self._failures and now - self._failures[0] > self.policy.window_s:
                self._failures.popleft()
            if len(self._failures) >= self.policy.failure_threshold:
                self._open(now)

    def _open(self, now: float) -> None:
        """Transition to OPEN and record the event once."""
        if self.state != "open":
            self.state = "open"
            self._event("circuit_open")
        self._opened_at = now
        self._half_open_inflight = 0
        self._half_open_successes = 0


@dataclass
class _CallSite:
    """Mutable runtime state for one resilience policy call site."""

    breaker: CircuitBreaker | None = None
    started: float = 0.0
    rng: random.Random | None = None


_SITES: dict[tuple[str, str, str], _CallSite] = {}
_SITES_LOCK = threading.Lock()


def reset_resilience_state() -> None:
    """Clear call-site breaker/fault state and report counters."""
    with _SITES_LOCK:
        _SITES.clear()
    reset_resilience_metrics()


def merge_resilience(base: ResilienceConfig | None, override: ResilienceConfig | None) -> ResilienceConfig:
    """Merge target-level resilience with explicitly configured stage overrides."""
    merged = (base or ResilienceConfig()).model_copy(deep=True)
    if override is None:
        return merged
    for field_name in override.model_fields_set:
        setattr(merged, field_name, getattr(override, field_name))
    return merged


def provider_retry_config(policy: RetryPolicy | None) -> dict[str, Any]:
    """Translate resilience.retry into the provider adapter retry config."""
    if policy is None or policy.attempts <= 0:
        return {}
    retry_on = set(policy.retry_on or [])
    mapped = []
    if "timeout" in retry_on:
        mapped.append("timeout")
    if "connect" in retry_on:
        mapped.append("connect")
    if "http_5xx" in retry_on:
        mapped.append("5xx")
    return {"max_retries": policy.attempts, "backoff_s": policy.backoff_s, "retry_on": mapped}


def _site(scenario: str, target: str, site: str, cfg: ResilienceConfig) -> _CallSite:
    """Return/create mutable state for one scenario/target/dependency site."""
    key = (scenario, target, site)
    with _SITES_LOCK:
        state = _SITES.get(key)
        if state is None:
            state = _CallSite(started=time.monotonic())
            _SITES[key] = state
        if cfg.circuit_breaker.enabled and state.breaker is None:
            state.breaker = CircuitBreaker(cfg.circuit_breaker, scenario, target, site)
        if state.rng is None:
            state.rng = random.Random(cfg.fault_injection.seed)
        return state


def _failure_kind(exc: BaseException) -> str:
    """Classify an exception into configured retry categories."""
    if isinstance(exc, (InjectedFault, OperationFailed)):
        return exc.kind
    if isinstance(exc, requests.HTTPError):
        status = getattr(getattr(exc, "response", None), "status_code", 0) or 0
        if status >= 500:
            return "http_5xx"
        if status >= 400:
            return "http_4xx"
    if isinstance(exc, (requests.Timeout, TimeoutError)):
        return "timeout"
    if isinstance(exc, (requests.ConnectionError, ConnectionError)):
        return "connect"
    return "exception"


def _failure_info(exc: BaseException) -> _FailureInfo:
    """Normalize exceptions into kind/message/result metadata."""
    return _FailureInfo(_failure_kind(exc), str(exc), getattr(exc, "result", None))


def _result_failure(value: Any, classifier: Callable[[Any], Any] | None) -> _FailureInfo | None:
    """Classify a successful-looking return value as a dependency failure."""
    if classifier is None:
        return None
    result = classifier(value)
    if result is None or result is False:
        return None
    if isinstance(result, _FailureInfo):
        return result
    if isinstance(result, tuple):
        return _FailureInfo(str(result[0]), str(result[1] if len(result) > 1 else result[0]), value)
    return _FailureInfo(str(result), str(result), value)


def _maybe_fault(
    state: _CallSite,
    cfg: ResilienceConfig,
    scenario: str,
    target: str,
    site: str,
) -> InjectedFault | None:
    """Return an injected operation fault when the configured window is active."""
    fault = cfg.fault_injection
    if not fault.enabled or fault.fault == "none":
        return None
    elapsed = time.monotonic() - state.started
    if elapsed < fault.after_s:
        return None
    if fault.duration_s is not None and elapsed > fault.after_s + fault.duration_s:
        return None
    if state.rng is not None and state.rng.random() > fault.probability:
        return None
    record_resilience_event(scenario, target, site, "fault_injection")
    if fault.fault == "latency":
        if fault.latency_s > 0:
            time.sleep(fault.latency_s)
        return None
    kinds = {
        "http_500": "http_5xx",
        "http_503": "http_5xx",
        "connect": "connect",
        "timeout": "timeout",
        "llm_error": "llm_error",
        "empty_response": "empty_response",
        "exception": "exception",
    }
    kind = kinds.get(fault.fault, "exception")
    return InjectedFault(kind, f"fault injection: {fault.fault}")


def _sleep_backoff(policy: RetryPolicy, attempt: int) -> None:
    """Apply capped exponential backoff plus jitter."""
    delay = min(policy.backoff_s * (2 ** (attempt - 1)), policy.max_backoff_s)
    if policy.jitter_s:
        delay += random.uniform(0, policy.jitter_s)
    if delay > 0:
        time.sleep(delay)


def _run_fallback(
    cfg: ResilienceConfig,
    fallback: Callable[[BaseException], Any] | None,
    exc: BaseException,
    scenario: str,
    target: str,
    site: str,
    attempts: int,
) -> ResilientResult:
    """Execute a configured fallback and record its outcome."""
    if cfg.fallback.type == "none":
        raise exc
    record_resilience_event(scenario, target, site, "fallback_invocation")
    failed_result = getattr(exc, "result", None)
    provider_retries = getattr(failed_result, "retries", 0) or 0
    if provider_retries:
        record_resilience_event(
            scenario,
            target,
            site,
            "retry_attempt",
            float(provider_retries),
        )
    if getattr(failed_result, "timed_out", False):
        record_resilience_event(scenario, target, site, "timeout")

    def unsupported():
        raise exc

    try:
        if fallback is not None:
            value = fallback(exc)
        elif cfg.fallback.type == "static_response":
            value = cfg.fallback.response or ""
        elif cfg.fallback.type == "empty_context":
            value = []
        elif cfg.fallback.type == "static_context":
            value = list(cfg.fallback.context)
        else:
            value = unsupported()
    except Exception:
        record_resilience_event(scenario, target, site, "fallback_success", 0.0)
        raise
    record_resilience_event(scenario, target, site, "fallback_success", 1.0)
    if cfg.fallback.mark_degraded:
        record_resilience_event(scenario, target, site, "degraded")
    if isinstance(value, ResilientResult):
        value.fallback_used = True
        value.degraded = cfg.fallback.mark_degraded or value.degraded
        value.attempts = attempts
        return value
    return ResilientResult(
        value=value,
        degraded=cfg.fallback.mark_degraded,
        fallback_used=True,
        attempts=attempts,
    )


def execute(
    *,
    scenario: str,
    target: str,
    site: str,
    resilience: ResilienceConfig | None,
    operation: Callable[[], Any],
    result_failure: Callable[[Any], Any] | None = None,
    fallback: Callable[[BaseException], Any] | None = None,
    retry_attempts: int | None = None,
) -> ResilientResult:
    """Run one dependency call under retry, breaker, fallback, and fault policy."""
    cfg = resilience or ResilienceConfig()
    state = _site(scenario, target, site, cfg)
    breaker = state.breaker
    permit = breaker.acquire() if breaker is not None else _Permit(True)
    if not permit.allowed:
        record_resilience_event(scenario, target, site, "circuit_rejected")
        return _run_fallback(
            cfg,
            fallback,
            CircuitOpen("circuit breaker is open"),
            scenario,
            target,
            site,
            0,
        )

    retry_cfg = cfg.retry
    attempts_limit = retry_cfg.attempts if retry_attempts is None else max(retry_attempts, 0)
    attempts = 0
    last_exc: BaseException | None = None
    while attempts <= attempts_limit:
        attempts += 1
        injected = _maybe_fault(state, cfg, scenario, target, site)

        def raise_injected(exc: BaseException):
            raise exc

        def raise_failure(failure: _FailureInfo):
            raise OperationFailed(failure.kind, failure.message, failure.result)

        try:
            if injected is not None:
                raise_injected(injected)
            value = operation()
            failure = _result_failure(value, result_failure)
            if failure is None:
                if breaker is not None:
                    breaker.success(permit)
                return ResilientResult(value=value, attempts=attempts)
            raise_failure(failure)
        except Exception as exc:
            failure = _failure_info(exc)
            last_exc = (
                exc
                if isinstance(exc, (OperationFailed, InjectedFault))
                else OperationFailed(failure.kind, failure.message, failure.result)
            )
            retryable = failure.kind in set(retry_cfg.retry_on or [])
            if attempts <= attempts_limit and retryable:
                record_resilience_event(scenario, target, site, "retry_attempt")
                _sleep_backoff(retry_cfg, attempts)
                continue
            provider_retries = getattr(failure.result, "retries", 0) or 0
            if provider_retries or (attempts_limit > 0 and failure.kind in set(retry_cfg.retry_on or [])):
                record_resilience_event(scenario, target, site, "retry_exhausted")
            if failure.kind == "timeout" and failure.result is None:
                record_resilience_event(scenario, target, site, "timeout")
            if breaker is not None:
                breaker.failure(permit)
            return _run_fallback(
                cfg,
                fallback,
                last_exc,
                scenario,
                target,
                site,
                attempts,
            )
    if last_exc is not None:
        raise last_exc
    raise OperationFailed("exception", "resilience operation failed")
